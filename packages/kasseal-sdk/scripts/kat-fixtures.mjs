#!/usr/bin/env node
// Record the known answers of the pinned Kaspa SDK into src/kat-fixtures.ts (see src/kat.ts). The answers come from
// the vendored web build (its files checked against packages/sdk/SHA256SUMS first) and must equal the answers of the
// vendored Node build. `--check` compares with the committed file instead of writing it.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const PKG = fileURLToPath(new URL('..', import.meta.url));
const SDK = path.resolve(PKG, '..', 'sdk');
const OUT = path.join(PKG, 'src', 'kat-fixtures.ts');
const check = process.argv.includes('--check');
const fail = (msg) => { console.error(`kat-fixtures: ${msg}`); process.exit(1); };
const sha256 = (b) => createHash('sha256').update(b).digest('hex');

const sums = new Map();
for (const line of readFileSync(path.join(SDK, 'SHA256SUMS'), 'utf8').split('\n')) {
  const m = /^([0-9a-f]{64})\s+\*?(.+)$/.exec(line.trim());
  if (m) sums.set(m[2], m[1]);
}
const pinned = (rel) => {
  const bytes = readFileSync(path.join(SDK, rel));
  if (sha256(bytes) !== sums.get(rel)) fail(`${rel} does not match SHA256SUMS`);
  return bytes;
};

const kat = await import(pathToFileURL(path.join(PKG, 'src', 'kat.ts')).href);

// The web build, as initWeb instantiates it.
pinned('vendor/web/kaspa/kaspa.js');
const web = await import(pathToFileURL(path.join(SDK, 'vendor/web/kaspa/kaspa.js')).href);
await web.default({ module_or_path: pinned('vendor/web/kaspa/kaspa_bg.wasm') });
// The Node build, through its checked loader.
const { loadSdk } = await import(pathToFileURL(path.join(SDK, 'src', 'load.mjs')).href);
const node = loadSdk();

// The test key's addresses are inputs of the cases: they must be what the pinned builds derive.
const keyHex = sha256(kat.KAT_TEST_KEY_LABEL);
for (const [name, k] of [['web', web], ['node', node]]) {
  for (const network of ['mainnet', 'testnet-10']) {
    const derived = new k.PrivateKey(keyHex).toPublicKey().toAddress(network).toString();
    if (derived !== kat.KAT_KEY_ADDRESS[network]) fail(`${name}: the test key's ${network} address is ${derived}; KAT_KEY_ADDRESS in src/kat.ts says ${JSON.stringify(kat.KAT_KEY_ADDRESS[network])}`);
  }
}

const t0 = performance.now();
const answers = kat.knownAnswers(web);
const ms = performance.now() - t0;
const nodeAnswers = kat.knownAnswers(node);
const errors = Object.entries(answers).filter(([k]) => k.endsWith('.error'));
if (errors.length > 0) fail(`a case threw on the pinned build: ${errors.map(([k, v]) => `${k}: ${v}`).join('; ')}`);
for (const [k, v] of Object.entries(answers)) if (k.endsWith('verifies') && v !== 'true') fail(`${k} is ${v} on the pinned build`);
if (answers.version !== '2.1.0') fail(`the pinned build reports ${answers.version}`);
const nodeDiff = kat.compareKnownAnswers(nodeAnswers, answers);
if (nodeDiff.length > 0) fail(`the Node build answers differently from the web build:\n  ${nodeDiff.join('\n  ')}`);

const sorted = Object.fromEntries(Object.keys(answers).sort().map((k) => [k, answers[k]]));
const text = [
  '// Generated by scripts/kat-fixtures.mjs from the pinned Kaspa SDK (rusty-kaspa 2.1.0 web build). Do not edit.',
  `export const KAT_FIXTURES: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(sorted, null, 1)});`,
  '',
].join('\n');
if (check) {
  if (readFileSync(OUT, 'utf8') !== text) fail('src/kat-fixtures.ts is not what the pinned build answers: run node scripts/kat-fixtures.mjs');
  console.log(`kat-fixtures: ${Object.keys(sorted).length} answers match (${ms.toFixed(0)} ms)`);
} else {
  writeFileSync(OUT, text);
  console.log(`kat-fixtures: wrote ${Object.keys(sorted).length} answers to src/kat-fixtures.ts (${ms.toFixed(0)} ms)`);
}
