/** The lot count of a family member with `lot` tokens per lot (800M tokens on the curve). */
export function standardCurveLots(lot: bigint): bigint {
  assertBigint(lot, 'lot');
  if (lot <= 0n || STANDARD_CURVE_TOKENS % lot !== 0n || (STANDARD_CURVE_TOKENS / lot) % 10n !== 0n) {
    throw new ParameterError(`lot ${lot} does not divide the Standard curve's 800M tokens into a multiple of 10 lots`);
  }
  return STANDARD_CURVE_TOKENS / lot;
}

/** Standard's shape: `p0 = k * L / 10` sompi per lot over `L = 800M / lot` lots (80,000 k for 1,000-token lots). */
export function standardShapeP0(lot: bigint, k: bigint): bigint {
  assertBigint(k, 'k');
  return (k * standardCurveLots(lot)) / 10n;
}

/**
 * The opening window of a family member in lots: `openWindowLots` (0: no window) and `openWindowMaxLots` (8M tokens),
 * the curve constructor's indices 17 and 18.
 */
export function standardOpeningWindow(lot: bigint): { readonly lots: bigint; readonly maxLots: bigint } {
  standardCurveLots(lot);
  return { lots: STANDARD_OPEN_WINDOW_TOKENS / lot, maxLots: STANDARD_OPEN_WINDOW_MAX_TOKENS / lot };
}

/** The preset name of a band: `standard-k<k>` (1,000-token lots), `standard-lot<lot/1000>k-k<k>` otherwise. */
export function standardBandName(spec: StandardBandSpec): string {
  assertBigint(spec.k, 'k');
  assertBigint(spec.lot, 'lot');
  if (spec.lot === L1K) return `standard-k${spec.k}`;
  if (spec.lot % 1_000n !== 0n) throw new ParameterError(`lot ${spec.lot} is not a whole number of thousands`);
  return `standard-lot${spec.lot / 1_000n}k-k${spec.k}`;
}

const STANDARD_BAND_NAME = /^standard-(?:lot([1-9][0-9]*)k-)?k([1-9][0-9]*)$/;

/**
 * The graduation-cap target of the family in US dollars: the anchor's graduation cap at its reference price,
 * 1,720,620.756 KAS x $0.0401 = $68,996.89 ("about $69k").
 */
export const STANDARD_TARGET_USD: number = kasOf(graduationMarketCapSompi(PRESET_STANDARD)) * PRESET_STANDARD_REFERENCE_KAS_USD;

function kasOf(sompi: bigint): number {
  return Number(sompi / SOMPI_PER_KAS) + Number(sompi % SOMPI_PER_KAS) / Number(SOMPI_PER_KAS);
}

/** `$0.0499`, `$4.91`: a band's reference price with three significant figures. */
function priceLabel(usd: number): string {
  return `$${usd.toPrecision(3)}`;
}

function bandPreset(spec: StandardBandSpec): LaunchPreset {
  const curveLots = standardCurveLots(spec.lot);
  const p: LaunchPreset = {
    ...PRESET_STANDARD,
    name: standardBandName(spec),
    curve: Object.freeze({ ...PRESET_STANDARD.curve, p0: standardShapeP0(spec.lot, spec.k), k: spec.k, curveLots }),
    lotSize: spec.lot,
    gradLots: STANDARD_GRAD_RESERVE_TOKENS / spec.lot,
  };
  const ref = STANDARD_TARGET_USD / kasOf(graduationMarketCapSompi(p));
  return Object.freeze({ ...p, label: `Standard — graduates ≈ $69k at ${priceLabel(ref)} KAS` });
}

/**
 * The family, ordered by graduation cap in KAS (ascending), i.e. by reference price descending: the band for the
 * highest KAS price first. The anchor `standard` is the one at $0.0401.
 */
export const STANDARD_FAMILY: readonly LaunchPreset[] = Object.freeze(
  [...STANDARD_BAND_SPECS.map(bandPreset), PRESET_STANDARD].sort((a, b) => {
    const ca = graduationMarketCapSompi(a);
    const cb = graduationMarketCapSompi(b);
    return ca < cb ? -1 : ca > cb ? 1 : 0;
  }),
);

/** The family's band presets (every member but the anchor). */
export const STANDARD_BANDS: readonly LaunchPreset[] = Object.freeze(STANDARD_FAMILY.filter((p) => p !== PRESET_STANDARD));

const BY_NAME = new Map(STANDARD_FAMILY.map((p) => [p.name, p]));
const INDEX = new Map(STANDARD_FAMILY.map((p, i) => [p.name, i]));
const REF = STANDARD_FAMILY.map((p) =>
  p === PRESET_STANDARD ? PRESET_STANDARD_REFERENCE_KAS_USD : STANDARD_TARGET_USD / kasOf(graduationMarketCapSompi(p)));

/** The family member of a preset name (`standard` or a committed band name), or undefined. */
export function standardFamilyPreset(name: string): LaunchPreset | undefined {
  return BY_NAME.get(name);
}

/** Whether `name` names a member of the Standard family. */
export function isStandardFamilyName(name: string): boolean {
  return BY_NAME.has(name);
}

/** Whether `name` has a band-name form (`standard-k<k>`, `standard-lot<n>k-k<k>`), committed or not (a builder refuses unknown ones). */
export function isStandardBandNameForm(name: string): boolean {
  return STANDARD_BAND_NAME.test(name);
}

/** The position of a family member in `STANDARD_FAMILY` (0 = the band for the highest KAS price), or undefined. */
export function standardFamilyIndex(name: string): number | undefined {
  return INDEX.get(name);
}

function memberIndex(preset: LaunchPreset): number {
  const i = INDEX.get(preset.name);
  if (i === undefined || STANDARD_FAMILY[i] !== preset) throw new ParameterError(`${preset.name} is not a member of the Standard family`);
  return i;
}

/** The KAS/USD price at which a family member graduates at exactly `STANDARD_TARGET_USD`. */
export function standardBandReferenceKasUsd(preset: LaunchPreset): number {
  return REF[memberIndex(preset)]!;
}

/**
 * The KAS/USD prices for which the family member at `i` is the nearest band: bounded by the geometric means of its
 * neighbours' reference prices, and at the family's ends by the tolerance.
 */
function servesAt(i: number): { min: number; max: number } {
  const n = STANDARD_FAMILY.length;
  return {
    max: i === 0 ? REF[0]! * (1 + STANDARD_BAND_TOLERANCE) : Math.sqrt(REF[i]! * REF[i - 1]!),
    min: i === n - 1 ? REF[n - 1]! / (1 + STANDARD_BAND_TOLERANCE) : Math.sqrt(REF[i]! * REF[i + 1]!),
  };
}

/** The KAS/USD prices for which `standardBandFor` picks this member. */
export function standardBandServes(preset: LaunchPreset): { readonly min: number; readonly max: number } {
  return servesAt(memberIndex(preset));
}

/** The KAS/USD prices the family serves: from the cheapest band's price / 1.05 to the dearest band's price x 1.05. */
export const STANDARD_FAMILY_RANGE_KAS_USD: Readonly<{ min: number; max: number }> = Object.freeze({
  min: servesAt(STANDARD_FAMILY.length - 1).min,
  max: servesAt(0).max,
});

/** The live price is outside the family's range: no band graduates within the tolerance of the target. */
export class StandardBandOutOfRange extends ParameterError {
  readonly kasUsd: number;
  constructor(kasUsd: number) {
    super(
      `KAS/USD ${kasUsd} is outside the Standard family's range ` +
        `(${STANDARD_FAMILY_RANGE_KAS_USD.min.toPrecision(3)} .. ${STANDARD_FAMILY_RANGE_KAS_USD.max.toPrecision(3)}): ` +
        `no band graduates within ${STANDARD_BAND_TOLERANCE * 100} % of the target`,
    );
    this.kasUsd = kasUsd;
  }
}

/** The band chosen for a launch at a given KAS/USD price (`standardBandFor`). */
export interface StandardBandChoice {
  /** The family member to launch with. */
  readonly preset: LaunchPreset;
  /** Its position in `STANDARD_FAMILY`. */
  readonly index: number;
  /** The live price the band was chosen at. */
  readonly kasUsd: number;
  /** The band's own reference price (graduates at exactly the target there). */
  readonly referenceKasUsd: number;
  /** The token's graduation market cap in KAS (fixed forever once launched), in sompi. */
  readonly graduationCapSompi: bigint;
  /** That cap in USD at the live price. */
  readonly graduationCapUsd: number;
  /** `graduationCapUsd / STANDARD_TARGET_USD - 1`: within [-1/21, +0.05]. */
  readonly deviation: number;
}

function assertPrice(kasUsd: number): void {
  if (typeof kasUsd !== 'number' || !Number.isFinite(kasUsd) || kasUsd <= 0) {
    throw new ParameterError(`kasUsd must be a finite positive number, got ${String(kasUsd)}`);
  }
}

/** The index of the band nearest `kasUsd` in log terms, ignoring the range (the extreme band beyond either end). */
function nearestIndex(kasUsd: number): { index: number; dist: number } {
  let best = { index: 0, dist: Number.POSITIVE_INFINITY };
  for (let i = 0; i < STANDARD_FAMILY.length; i++) {
    const dist = Math.abs(Math.log(kasUsd / REF[i]!));
    if (dist < best.dist) best = { index: i, dist };
  }
  return best;
}

/**
 * The family member a launch at `kasUsd` uses: the band whose graduation cap at that price is nearest the target in
 * log terms (so the boundary between two bands is the geometric mean of their reference prices). Throws
 * `StandardBandOutOfRange` when even the nearest band misses the target by more than the tolerance, and
 * `ParameterError` for a price that is not a finite positive number.
 */
export function standardBandFor(kasUsd: number): StandardBandChoice {
  assertPrice(kasUsd);
  const { index, dist } = nearestIndex(kasUsd);
  if (dist > Math.log(1 + STANDARD_BAND_TOLERANCE) + 1e-12) throw new StandardBandOutOfRange(kasUsd);
  const preset = STANDARD_FAMILY[index]!;
  const capUsd = kasOf(graduationMarketCapSompi(preset)) * kasUsd;
  return {
    preset,
    index,
    kasUsd,
    referenceKasUsd: REF[index]!,
    graduationCapSompi: graduationMarketCapSompi(preset),
    graduationCapUsd: capUsd,
    deviation: capUsd / STANDARD_TARGET_USD - 1,
  };
}

/** Why a launch's band was refused against the price at its launch time (`checkStandardBand`). */
export type StandardBandRefusal = 'not-a-band' | 'price-out-of-range' | 'wrong-band';

/** The result of `checkStandardBand`. */
export interface StandardBandVerdict {
  /** Whether the launch's band fits the price. */
  readonly accepted: boolean;
  /** Set when refused. */
  readonly reason: StandardBandRefusal | undefined;
  /** The launched preset's position in the family (undefined for a name outside it). */
  readonly index: number | undefined;
  /** The band the price calls for (undefined when the price is outside the family's range). */
  readonly expected: LaunchPreset | undefined;
  /** `|index - expected index|` in bands (undefined when either is). */
  readonly distance: number | undefined;
  /** The KAS/USD prices at which this launch's band is accepted (undefined for a name outside the family). */
  readonly accepts: { readonly min: number; readonly max: number } | undefined;
  /** A sentence for a 409 or a refusal note. */
  readonly message: string;
}

/**
 * The off-chain band rule: a launch on the family member `name` at the KAS/USD price
 * `kasUsd` (the price at its launch time) is accepted when that price lies in the range served by the member or by one
 * of its `toleranceBands` neighbours on either side; the family's ends are not extended (a price beyond the range is
 * refused for every band). The builder applies it with `toleranceBands = 0` (the band of the price the app showed),
 * the Kasseal API with `STANDARD_BAND_ACCEPT_BANDS` (the price may move during a launch).
 */
export function checkStandardBand(name: string, kasUsd: number, toleranceBands: number = STANDARD_BAND_ACCEPT_BANDS): StandardBandVerdict {
  assertPrice(kasUsd);
  if (!Number.isInteger(toleranceBands) || toleranceBands < 0) throw new ParameterError(`toleranceBands must be a non-negative integer, got ${toleranceBands}`);
  const index = INDEX.get(name);
  const near = nearestIndex(kasUsd);
  const inRange = near.dist <= Math.log(1 + STANDARD_BAND_TOLERANCE) + 1e-12;
  const expected = inRange ? STANDARD_FAMILY[near.index] : undefined;
  if (index === undefined) {
    return { accepted: false, reason: 'not-a-band', index, expected, distance: undefined, accepts: undefined, message: `${name} is not a Standard band` };
  }
  const n = STANDARD_FAMILY.length;
  const accepts = { max: servesAt(Math.max(0, index - toleranceBands)).max, min: servesAt(Math.min(n - 1, index + toleranceBands)).min };
  const distance = inRange ? Math.abs(index - near.index) : undefined;
  const fmt = (v: number): string => `$${v.toPrecision(3)}`;
  if (!inRange) {
    return {
      accepted: false, reason: 'price-out-of-range', index, expected, distance, accepts,
      message: `KAS at ${fmt(kasUsd)} is outside the Standard bands' range (${fmt(STANDARD_FAMILY_RANGE_KAS_USD.min)} .. ${fmt(STANDARD_FAMILY_RANGE_KAS_USD.max)})`,
    };
  }
  const accepted = kasUsd >= accepts.min && kasUsd <= accepts.max;
  return {
    accepted, reason: accepted ? undefined : 'wrong-band', index, expected, distance, accepts,
    message: accepted
      ? `${name} is accepted at KAS ${fmt(kasUsd)}`
      : `${name} is the band for KAS at ${fmt(REF[index]!)}, ${distance} bands from the band for KAS at ${fmt(kasUsd)} (${expected!.name}); ` +
        `it is accepted only for ${fmt(accepts.min)} .. ${fmt(accepts.max)}`,
  };
}
