/**
 * The Standard family: one Standard curve per KAS/USD price band, so a launch graduates at about the same US-dollar
 * market cap whatever KAS trades at.
 *
 * The problem. A curve's graduation target is fixed in KAS: Standard raises 573,540.252 KAS and graduates at a
 * market cap of 1,720,620.756 KAS, about $69k at KAS = $0.0401. If KAS doubles the same curve graduates at about
 * $138k, if it halves at about $35k. The contracts never read a price (no oracle: every on-chain price stays in
 * KAS), so the dollar target can only be held by choosing the curve at launch, and enforced off chain (the builder
 * against the price the app showed, the Kasseal API against its price history: `checkStandardBand`).
 *
 * The family. Every member sells 800M tokens on the curve and keeps 400M for the pool, with Standard's shape: over
 * `L = 800M / lot` lots, `p0 = k * L / 10` sompi per lot (the 100,000-token rule K = 10 * P0 / 8,000 of Set A and
 * the original Standard), so the last lot is (1.1 L - 1) / (0.1 L), about 11 x the first, the pool opens about
 * +9.09 % over the last lot, and every figure is linear in the integer slope `k`:
 *
 *   raise(lot, k)          = k * L * (L / 10 + (L - 1) / 2)
 *                          = k * 3,839.996 KAS   (1,000-token lots, L = 800,000)
 *                          = k * 38.3996 KAS     (10,000-token lots, L = 80,000)
 *   graduation cap(lot, k) = 3 * raise(lot, k)
 *
 * Granularity. `k` is an integer, so the step between two neighbouring k is 1 / k: fine for k in the hundreds, far too
 * coarse at high KAS prices (with 1,000-token lots k = 1 is the target at about $6). The bands above $0.061 therefore
 * use 10,000-token lots: the same token amounts (800M / 400M, an 80M-token opening window with at most 8M tokens per
 * buy), 100 x the k for the same cap, so k stays above 120 up to $5. The UI is token-first, so the lot is invisible.
 *
 * The bands. From the anchor (the committed `standard` preset, k = 149 with p0 solved for its 573,540.252 KAS raise,
 * kept byte for byte for the tokens already launched on it) outwards, each next band is the integer k whose cap is
 * the furthest from its neighbour's within `STANDARD_BAND_RATIO_MAX` (1.1025 = 1.05^2), 1,000-token lots while k >= 100
 * and 10,000-token lots above. Picking the band nearest the live price (in log terms) then keeps the graduation cap at
 * launch within `[target / 1.05, target * 1.05]`; a price outside the family's range ($0.00907 .. $5.15) is refused
 * rather than served by a band that would miss the target (`standardBandFor`).
 *
 * The factory's final-tranche rule asks for a fee of at least 0.1 KAS on the final 10,000,000 tokens; every band passes
 * with at least 0.88 KAS, so that rule does not bound the family.
 */

import { ParameterError } from './errors.ts';
import { assertBigint } from './int64.ts';
import {
  PRESET_STANDARD, PRESET_STANDARD_REFERENCE_KAS_USD, SOMPI_PER_KAS, graduationMarketCapSompi, type LaunchPreset,
} from './presets.ts';

/** Tokens every family member sells on the curve (800M). */
export const STANDARD_CURVE_TOKENS = 800_000_000n;
/** Tokens every family member hands the pool at graduation (400M). */
export const STANDARD_GRAD_RESERVE_TOKENS = 400_000_000n;
/**
 * The opening window in tokens: none (there is no per-buy cap at launch). The curve keeps the rule
 * (a buy takes at most openWindowMaxLots while lotsSold < openWindowLots); with 0 it never applies...
 */
export const STANDARD_OPEN_WINDOW_TOKENS = 0n;
/** ...and the per-buy cap it would have, which the curve requires to be positive (8M tokens). */
export const STANDARD_OPEN_WINDOW_MAX_TOKENS = 8_000_000n;

/** The lot sizes the family uses: 1,000 tokens (the anchor's) and 10,000 tokens (the bands above $0.061). */
export const STANDARD_BAND_LOTS: readonly bigint[] = Object.freeze([1_000n, 10_000n]);

/** A band: its lot size (tokens per lot) and its integer slope `k` (sompi per lot). */
export interface StandardBandSpec {
  /** Tokens per lot. */
  readonly lot: bigint;
  /** The curve slope, sompi per lot. */
  readonly k: bigint;
}

/** The ratio between two neighbouring bands' graduation caps is at most this (so a band is at most sqrt(1.1025) = 1.05 off). */
export const STANDARD_BAND_RATIO_MAX = 1.1025;

/** The graduation cap at the live price stays within `[target / (1 + t), target * (1 + t)]`; outside, the launch is refused. */
export const STANDARD_BAND_TOLERANCE = 0.05;

/**
 * How many bands a launch may be off the band of the KAS/USD price at its launch time and still be accepted (the
 * price can move between the moment the app picked the band and the moment the Kasseal API sees the launch).
 */
export const STANDARD_BAND_ACCEPT_BANDS = 1;

const L1K = 1_000n;
const L10K = 10_000n;

